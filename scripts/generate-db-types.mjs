import { PGlite } from '@electric-sql/pglite'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { bootstrapSql } from './lib/test-bootstrap.mjs'

const db = new PGlite()
try {
  await db.exec(bootstrapSql)
  for (const file of (await readdir('supabase/migrations')).filter(name => name.endsWith('.sql')).sort()) {
    await db.exec(await readFile(`supabase/migrations/${file}`, 'utf8'))
  }
  const enums = (await db.query(`select t.typname, array_agg(e.enumlabel order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by t.typname order by t.typname`)).rows
  const columns = (await db.query(`select table_name, column_name, data_type, udt_name, is_nullable
    from information_schema.columns where table_schema = 'public'
    order by table_name, ordinal_position`)).rows
  const enumNames = new Set(enums.map(e => e.typname))
  let source = '// Generated by npm run types:db from versioned SQL in local PostgreSQL (PGlite).\n'
    + '// Not introspected from a remote project. Row types only; not client write permissions.\n\n'
    + 'export interface DatabaseEnums {\n'
  for (const e of enums) source += `  ${e.typname}: ${e.labels.map(label => JSON.stringify(label)).join(' | ')}\n`
  source += '}\n\nexport interface DatabaseRows {\n'
  for (const table of [...new Set(columns.map(c => c.table_name))]) {
    source += `  ${table}: {\n`
    for (const column of columns.filter(c => c.table_name === table)) {
      let type = enumNames.has(column.udt_name) ? `DatabaseEnums['${column.udt_name}']`
        : column.data_type === 'boolean' ? 'boolean'
        : ['integer','bigint','double precision','smallint','numeric'].includes(column.data_type) ? 'number' : 'string'
      if (column.is_nullable === 'YES') type += ' | null'
      source += `    ${column.column_name}: ${type}\n`
    }
    source += '  }\n'
  }
  source += '}\n'
  await writeFile('src/types/database.generated.ts', source)
  console.log(`Generated row types for ${new Set(columns.map(c => c.table_name)).size} tables and ${enums.length} enums from local migrations.`)
} finally { await db.close() }
